/**
 * Universal translation getter with multi-level fallback:
 * 1. Target language dictionary (e.g. 'mr-IN')
 * 2. Short language code dictionary (e.g. 'mr')
 * 3. Hindi dictionary if Indic language
 * 4. English dictionary
 * 5. Key itself
 */
export function t(key, langCode = 'en-IN') {
  if (!key) return '';

  const targetLang = langCode || 'en-IN';
  const shortLang = targetLang.split('-')[0];

  // 1. Check exact locale in TRANSLATIONS
  if (TRANSLATIONS[targetLang] && TRANSLATIONS[targetLang][key] !== undefined) {
    return TRANSLATIONS[targetLang][key];
  }

  // 2. Check short language code if stored as 'hi', 'mr', etc.
  for (const dictKey of Object.keys(TRANSLATIONS)) {
    if (dictKey.startsWith(shortLang) && TRANSLATIONS[dictKey][key] !== undefined) {
      return TRANSLATIONS[dictKey][key];
    }
  }

  // 3. Fallback to Hindi for Indic scripts if available, or English
  const isIndic = ['hi', 'mr', 'ne', 'sa', 'mai', 'doi', 'kok', 'ks', 'sd'].includes(shortLang);
  if (isIndic && TRANSLATIONS['hi-IN'] && TRANSLATIONS['hi-IN'][key] !== undefined) {
    return TRANSLATIONS['hi-IN'][key];
  }

  // 4. Default fallback to English
  if (TRANSLATIONS['en-IN'] && TRANSLATIONS['en-IN'][key] !== undefined) {
    return TRANSLATIONS['en-IN'][key];
  }

  return key;
}
